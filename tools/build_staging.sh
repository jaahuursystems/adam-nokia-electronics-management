#!/bin/sh
# Regenerates docs/staging/ from docs/ (the single source), pointed at the STAGING backend.
# Usage: tools/build_staging.sh "<staging /exec URL>"   (the /exec URL is public by design; security is token-based)
set -e
URL="$1"; [ -n "$URL" ] || { echo "usage: $0 <staging exec url>"; exit 1; }
rm -rf docs/staging.tmp; mkdir docs/staging.tmp
for f in index.html manifest.webmanifest sw.js css js assets; do cp -r docs/$f docs/staging.tmp/; done
rm -rf docs/staging; mv docs/staging.tmp docs/staging
printf '/* STAGING backend (fake test data). Generated by tools/build_staging.sh */\nwindow.ANE_CONFIG = {\n  API_URL: %s\n};\n' "\"$URL\"" > docs/staging/js/config.js
sed -i "s/ane-shell-v4-production/ane-shell-v4-staging/" docs/staging/sw.js
sed -i 's#<title>Adam Nokia Electronics#<title>STAGING — Adam Nokia Electronics#; s#<body>#<body><div style="position:fixed;left:8px;bottom:8px;z-index:99999;background:\#F5A623;color:\#001A6E;font:700 11px Poppins,sans-serif;padding:3px 8px;border-radius:6px;pointer-events:none">STAGING · TEST DATA</div>#' docs/staging/index.html
sed -i 's#"name": "Adam Nokia Electronics"#"name": "ANE STAGING"#; s#"short_name": "Adam Nokia"#"short_name": "ANE Staging"#' docs/staging/manifest.webmanifest
echo "docs/staging built for $URL"
